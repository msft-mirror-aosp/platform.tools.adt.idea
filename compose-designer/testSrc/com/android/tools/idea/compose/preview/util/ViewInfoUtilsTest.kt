package com.android.tools.idea.compose.preview.util

import com.android.tools.compose.COMPOSE_VIEW_ADAPTER_FQN
import com.google.common.truth.Truth.assertThat
import org.jetbrains.org.objectweb.asm.ClassWriter
import org.jetbrains.org.objectweb.asm.Opcodes
import org.junit.Test

class ViewInfoUtilsTest {

  private class FakeViewGroup(private vararg val children: Any?) {
    fun getChildCount(): Int = children.size

    fun getChildAt(index: Int): Any? = children[index]
  }

  private class FakeLeafView

  /**
   * Dynamically generates and instantiates an empty class matching [COMPOSE_VIEW_ADAPTER_FQN] inside an isolated [ClassLoader], avoiding
   * global test classpath pollution for other tests in this module.
   *
   * Equivalent Java source code generated by ASM below:
   * ```java
   * package androidx.compose.ui.tooling;
   *
   * public class ComposeViewAdapter extends Object {
   *   public ComposeViewAdapter() {
   *     super();
   *   }
   * }
   * ```
   */
  private fun createComposeViewAdapterInstance(): Any {
    val internalName = COMPOSE_VIEW_ADAPTER_FQN.replace('.', '/')
    val cw = ClassWriter(0)
    // Declare class: public class androidx.compose.ui.tooling.ComposeViewAdapter extends Object
    cw.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, internalName, null, "java/lang/Object", null)

    // Declare no-arg constructor: public ComposeViewAdapter() { super(); }
    val ctor = cw.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null)
    ctor.visitCode()
    ctor.visitVarInsn(Opcodes.ALOAD, 0) // push `this` onto operand stack
    ctor.visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false)
    ctor.visitInsn(Opcodes.RETURN)
    ctor.visitMaxs(1, 1) // max stack = 1 (`this`), max locals = 1 (`this`)
    ctor.visitEnd()

    cw.visitEnd()
    val bytes = cw.toByteArray()

    // Load the generated bytecode through an isolated ClassLoader so it only exists for this call.
    val loader =
      object : ClassLoader(null) {
        override fun findClass(name: String): Class<*> {
          if (name == COMPOSE_VIEW_ADAPTER_FQN) {
            return defineClass(name, bytes, 0, bytes.size)
          }
          throw ClassNotFoundException(name)
        }
      }
    return loader.loadClass(COMPOSE_VIEW_ADAPTER_FQN).getDeclaredConstructor().newInstance()
  }

  @Test
  fun returnsRootWhenRootIsComposeViewAdapter() {
    val adapter = createComposeViewAdapterInstance()

    assertThat(findComposeViewAdapter(adapter)).isSameAs(adapter)
  }

  @Test
  fun findsComposeViewAdapterAtFirstChild() {
    val adapter = createComposeViewAdapterInstance()
    val root = FakeViewGroup(adapter, FakeViewGroup())

    assertThat(findComposeViewAdapter(root)).isSameAs(adapter)
  }

  @Test
  fun findsComposeViewAdapterAtNonZeroChildIndexAfterEmptyAndLeafSiblings() {
    val adapter = createComposeViewAdapterInstance()
    val root =
      FakeViewGroup(
        FakeLeafView(),
        FakeViewGroup(),
        FakeViewGroup(FakeLeafView(), FakeViewGroup()),
        adapter,
      )

    assertThat(findComposeViewAdapter(root)).isSameAs(adapter)
  }

  @Test
  fun findsComposeViewAdapterNestedInsideLaterSiblingSubtree() {
    val adapter = createComposeViewAdapterInstance()
    val root =
      FakeViewGroup(
        FakeViewGroup(FakeViewGroup(), FakeLeafView()),
        FakeViewGroup(FakeLeafView(), FakeViewGroup(FakeViewGroup(), adapter)),
      )

    assertThat(findComposeViewAdapter(root)).isSameAs(adapter)
  }

  @Test
  fun returnsNullWhenComposeViewAdapterIsNotPresent() {
    val root = FakeViewGroup(FakeLeafView(), FakeViewGroup(FakeViewGroup(), FakeLeafView()))

    assertThat(findComposeViewAdapter(root)).isNull()
  }

  @Test
  fun skipsNullChildAndContinuesSearchingSiblings() {
    val adapter = createComposeViewAdapterInstance()
    val rootWithAdapter = FakeViewGroup(null, adapter)
    val rootWithoutAdapter = FakeViewGroup(null, FakeLeafView())

    assertThat(findComposeViewAdapter(rootWithAdapter)).isSameAs(adapter)
    assertThat(findComposeViewAdapter(rootWithoutAdapter)).isNull()
  }
}
