private val LOG = Logger.getInstance(FindingsInsightToolkit::class.java)
private val HTTPS_URL_REGEX = Regex("""https://[^\s"\\]+""")
private val SUPPORTED_TEXT_MIME_TYPES = setOf("text/plain", "text/xml", "application/xml", "application/json")

/**
 * Play Findings implementation of [AiInsightBaseToolkit].
 *
 * Unlike Crashlytics and Play Vitals—which subclass [com.android.tools.idea.insights.ai.AiInsightToolkit] and operate on crash
 * [com.android.tools.idea.insights.model.event.Event]s—Play Findings operates on [AppFinding] models. This class extends
 * [AiInsightBaseToolkit] to share model-independent AI settings, deprecation checks, and contributor helpers (`isAutoGenerateEnabled`,
 * `setAutoGenerate`, `isModelAvailable`, `handleModelAssignment`, `showOnboarding`) while providing an [AppFinding]-based pipeline.
 *
 * Owns both AI entry points for a Play Console [AppFinding]:
 * - [fetchInsight]: Evaluates service deprecation, contributor/model availability, and auto-generate settings before generating a short,
 *   text-only summary insight displayed in [FindingsInsightPanel] ([ResolvedPayload.formatTextOnly]).
 * - [submitQueryToAgent]: Opens an interactive agent chat session ("See more" / "Fix with AI") with the finding's [AppFinding.jsonPayload]
 *   and text attachments attached as [LlmUserQueryPayload.Reference]s and screenshots attached separately as [LlmBlob]s
 *   ([ResolvedPayload.formatMultimodal]).
 *
 * Remote finding assets (view hierarchy XMLs and screenshots) are resolved through the project-level [FindingsAssetLoader] in-memory cache,
 * reusing bytes already downloaded by [FindingsDetailsPanel] on cache hit and fetching over HTTPS only on cache miss.
 */
// TODO(b/517599039): Unify FindingsInsightToolkit and AiInsightToolkit into a single composition-based insight pipeline.
open class FindingsInsightToolkit(project: Project) : AiInsightBaseToolkit(project) {

  // TODO(b/517599039): Add in-memory caching of generated insights (and feedback) keyed by finding name.
  open suspend fun fetchInsight(
    finding: AppFinding,
    forceGenerateNewInsight: Boolean = false,
  ): LoadingState.Done<AiInsight> {
    return try {
      if (insightDeprecationData.isUnsupported()) {
        return LoadingState.ServiceUnsupported
      }
      // TODO(b/517599039): Replace LoadingState.Unauthorized with a dedicated plugin-unavailable state
      //  when migrating currentInsight from LoadingState<AiInsight> to a dedicated InsightState hierarchy.
      val contributor =
        AiInsightContributor.getFirstAvailableContributor() ?: return LoadingState.Unauthorized("No insight contributor found")
      if (!isModelAvailable()) {
        return LoadingState.NoModelAvailable
      }
      if (!isAutoGenerateEnabled() && !forceGenerateNewInsight) {
        return LoadingState.InsightAutogenerateDisabled
      }
      val prompt = createFindingPrompt(finding)
      val failure = LoadingState.UnknownFailure("Unable to fetch insight for the selected finding.")
      runGrpcCatching(failure) {
        val insight = contributor.fetchInsight(project, AiInsightRequest(prompt))
        LoadingState.Ready(insight)
      }
    } catch (e: CancellationException) {
      throw e
    } catch (e: Exception) {
      LoadingState.UnknownFailure(e.message ?: "Unable to fetch insight for the selected finding.", e)
    }
  }

  open suspend fun submitQueryToAgent(query: String, finding: AppFinding) {
    try {
      val formatted =
        withContext(Dispatchers.IO) {
          resolvePayload(finding.jsonPayload).formatMultimodal()
        }
      // Attach the finding JSON and any text files as hidden IDE context so the user's chat bubble only displays the short `query`.
      // An empty [0, 0) text range covers no part of `query`, so no inline reference chip is rendered in the message bubble.
      val payloads = buildList {
        add(
          LlmUserQueryPayload.Reference(
            promptString = formatted.json.sanitizeForPrompt(),
            textRangeStart = 0,
            textRangeEnd = 0,
          )
        )
        for (attachment in formatted.textAttachments) {
          add(
            LlmUserQueryPayload.Reference(
              promptString = "${attachment.label}\n${attachment.content.sanitizeForPrompt()}",
              textRangeStart = 0,
              textRangeEnd = 0,
            )
          )
        }
      }
      // TODO(b/517599039): Consider unifying how AQI chat actions are sent: Crash uses AgentActionContributor (injecting
      // DOMAIN_INSTRUCTIONS via AgentConfiguration), whereas Findings uses GeminiPluginApiV2 with Reference payloads and LlmBlobs.
      when (
        val result =
          GeminiPluginApiV2.getInstance()
            .submitQueryWithPayloadsInToolWindow(
              project = project,
              query = query,
              blobs = formatted.images,
              payloads = payloads,
            )
      ) {
        is LlmChatInToolWindowResult.Success -> {
          LOG.info("Successfully submitted query to Gemini tool window.")
        }
        is LlmChatInToolWindowResult.RequestNotSubmitted -> {
          LOG.warn("Failed to submit query to Gemini tool window: ${result.reason}")
          val message =
            when (result.reason) {
              LlmFailureReason.NO_MODELS_AVAILABLE -> "Please ensure an AI model is configured and available."
            }
          AndroidNotification.getInstance(project).showBalloon("Play Findings", message, NotificationType.WARNING)
        }
      }
    } catch (e: CancellationException) {
      throw e
    } catch (e: Exception) {
      LOG.warn("Exception while submitting query to Gemini tool window", e)
    }
  }

  /**
   * Builds the prompt for the AI Insights panel: an explicit instruction followed by [finding]'s [AppFinding.jsonPayload] in a fenced block
   * and any attached text files (see [resolvePayload]). Image URLs are replaced with `[Screenshot omitted]` because [AiInsightRequest] only
   * carries a prompt string.
   */
  @VisibleForTesting
  internal suspend fun createFindingPrompt(finding: AppFinding): String {
    val formatted = resolvePayload(finding.jsonPayload).formatTextOnly()
    return buildString {
      append(String.format(FINDING_INSIGHT_PROMPT_FORMAT, formatted.json.sanitizeForPrompt()).trim())
      for (attachment in formatted.textAttachments) {
        append("\n\n${attachment.label}\n")
        append(attachment.content.sanitizeForPrompt())
      }
    }
  }

  /**
   * Resolves each distinct HTTPS URL in [payload] via [FindingsAssetLoader] (reusing cached bytes when already loaded):
   * - Image assets (`image/` MIME type) are collected as [ResolvedAsset.Image].
   * - Supported text assets ([SUPPORTED_TEXT_MIME_TYPES], such as view hierarchy XMLs) are collected as [ResolvedAsset.TextFile].
   * - If an asset fails to load, a warning is logged and its URL is omitted from [ResolvedPayload] so the original URL is preserved.
   * - Assets with other or missing MIME types (such as HTML documentation pages or binary recordings) are skipped and keep their URL.
   */
  @VisibleForTesting
  internal suspend fun resolvePayload(payload: String): ResolvedPayload {
    val assetLoader = FindingsAssetLoader.getInstance(project)
    val assetsByUrl = linkedMapOf<String, ResolvedAsset>()
    // TODO(b/581970782): Walk parsed JSON values and preflight Content-Type headers so non-asset links are not fetched and screenshots are
    // not downloaded on cache miss for the text-only prompt.
    for (url in HTTPS_URL_REGEX.findAll(payload).map { it.value }.distinct()) {
      try {
        val asset = assetLoader.loadAsset(url)
        val mimeType = asset.mimeType ?: continue
        when {
          mimeType.startsWith("image/") -> {
            // TODO(b/517599039): Clicking an image blob chip in the Agent tool window currently creates a new BinaryLightVirtualFile and
            // opens a duplicate editor tab on every click; update the Agent tool window image preview handler to reuse an already-open tab.
            assetsByUrl[url] = ResolvedAsset.Image(LlmBlob(data = asset.bytes, mimeType = mimeType))
          }
          mimeType in SUPPORTED_TEXT_MIME_TYPES -> {
            val content = asset.bytes.toString(Charsets.UTF_8)
            if (content.isNotBlank()) {
              assetsByUrl[url] = ResolvedAsset.TextFile(content)
            }
          }
        }
      } catch (e: CancellationException) {
        throw e
      } catch (e: Exception) {
        LOG.warn("Failed to load finding asset from $url", e)
      }
    }
    return ResolvedPayload(rawJson = payload, assetsByUrl = assetsByUrl)
  }
}

internal sealed interface ResolvedAsset {
  data class Image(val blob: LlmBlob) : ResolvedAsset

  data class TextFile(val content: String) : ResolvedAsset
}

internal class ResolvedPayload(
  private val rawJson: String,
  private val assetsByUrl: Map<String, ResolvedAsset>,
) {
  internal data class TextAttachment(val label: String, val content: String)

  internal data class Formatted(
    val json: String,
    val textAttachments: List<TextAttachment>,
    val images: List<LlmBlob>,
  )

  /**
   * Formats [rawJson] for a text-only prompt: replaces loaded image URLs with `[Screenshot omitted]` and numbers text attachments
   * sequentially starting from `[Attachment 1]`.
   */
  fun formatTextOnly(): Formatted = format(includeImages = false)

  /**
   * Formats [rawJson] for multimodal agent queries: numbers both image and text assets sequentially as `[Attachment 1..N]`, collecting
   * screenshots in [Formatted.images] and text files in [Formatted.textAttachments].
   */
  fun formatMultimodal(): Formatted = format(includeImages = true)

  private fun format(includeImages: Boolean): Formatted {
    val replacements = mutableMapOf<String, String>()
    val textAttachments = mutableListOf<TextAttachment>()
    val images = mutableListOf<LlmBlob>()
    var attachmentIndex = 0
    for ((url, asset) in assetsByUrl) {
      when (asset) {
        is ResolvedAsset.Image -> {
          if (includeImages) {
            replacements[url] = "[Attachment ${++attachmentIndex}]"
            images += asset.blob
          } else {
            replacements[url] = "[Screenshot omitted]"
          }
        }
        is ResolvedAsset.TextFile -> {
          val label = "[Attachment ${++attachmentIndex}]"
          replacements[url] = label
          textAttachments += TextAttachment(label, asset.content)
        }
      }
    }
    // Replace in a single pass so that a URL that is a prefix of another URL is not rewritten.
    val resolvedJson = if (replacements.isEmpty()) rawJson else HTTPS_URL_REGEX.replace(rawJson) { replacements[it.value] ?: it.value }
    return Formatted(json = resolvedJson, textAttachments = textAttachments, images = images)
  }
}

private val FINDING_INSIGHT_PROMPT_FORMAT =
  """
  Explain this Google Play Console finding for my app and how to fix it:
  Finding:
  ```
  %s
  ```
  """
    .trimIndent()
